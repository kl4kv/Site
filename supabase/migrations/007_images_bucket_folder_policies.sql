-- Миграция: Обновление RLS политик для бакета images с поддержкой папок
-- Описание: Разделение доступа по папкам (general, blog/covers, blog/content)

-- ============================================
-- UP миграция
-- ============================================

-- Удаляем существующие политики для бакета images
DROP POLICY IF EXISTS "Публичный доступ на чтение изображений" ON storage.objects;
DROP POLICY IF EXISTS "Публичная загрузка изображений" ON storage.objects;
DROP POLICY IF EXISTS "Публичное удаление изображений" ON storage.objects;

-- ============================================
-- Политика 1: Публичный доступ на чтение всех изображений
-- ============================================
CREATE POLICY "Публичный доступ на чтение изображений"
  ON storage.objects
  FOR SELECT
  USING (bucket_id = 'images');

-- ============================================
-- Политика 2: Загрузка изображений для аутентифицированных пользователей
-- Разрешаем загрузку в любые папки бакета images
-- ============================================
CREATE POLICY "Загрузка изображений авторизованными пользователями"
  ON storage.objects
  FOR INSERT
  TO authenticated
  WITH CHECK (bucket_id = 'images');

-- ============================================
-- Политика 3: Удаление изображений для аутентифицированных пользователей
-- ============================================
CREATE POLICY "Удаление изображений авторизованными пользователями"
  ON storage.objects
  FOR DELETE
  TO authenticated
  USING (bucket_id = 'images');

-- ============================================
-- Политика 4: Обновление метаданных изображений
-- ============================================
CREATE POLICY "Обновление метаданных изображений"
  ON storage.objects
  FOR UPDATE
  TO authenticated
  USING (bucket_id = 'images');

